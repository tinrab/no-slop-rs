fn write(root: &Path, path: &str, source: &str) {
    let path = root.join(path);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, source).unwrap();
}

fn workspace() -> TempDir {
    let directory = tempfile::tempdir().unwrap();
    write(
        directory.path(),
        "Cargo.toml",
        r#"
        [workspace]
        members = ["a", "a/nested"]
        resolver = "2"
        [workspace.metadata.no-slop]
        exclude = ["a/src/excluded.rs"]
    "#,
    );
    write(
        directory.path(),
        "a/Cargo.toml",
        "[package]\nname = \"a\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
    );
    write(
        directory.path(),
        "a/nested/Cargo.toml",
        "[package]\nname = \"nested\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
    );
    write(
        directory.path(),
        "a/src/lib.rs",
        "fn f() -> Result<(), String> { loop {} }",
    );
    write(directory.path(), "a/src/excluded.rs", "not Rust");
    write(
        directory.path(),
        "a/src/generated.rs",
        "// @generated\nnot Rust",
    );
    write(directory.path(), "a/vendor/f.rs", "not Rust");
    write(directory.path(), "a/target/f.rs", "not Rust");
    write(
        directory.path(),
        "a/tests/integration.rs",
        "fn test_f() -> Result<(), String> { loop {} }",
    );
    write(
        directory.path(),
        "a/nested/src/lib.rs",
        "#[cfg(feature = \"disabled\")] struct UserData;",
    );
    directory
}

fn options(root: &Path) -> Options {
    Options {
        manifest_path: Some(root.join("Cargo.toml")),
        ..Options::default()
    }
}

#[test]
fn test_workspace_selection_nested_members_exclusions_and_uncompiled_code() {
    let directory = workspace();
    let first = scan(&options(directory.path())).unwrap();
    let second = scan(&options(directory.path())).unwrap();
    assert!(first.failures.is_empty(), "{:?}", first.failures);
    assert_eq!(first.summary.scanned, 3);
    assert_eq!(first.diagnostics.len(), 2);
    assert_eq!(
        serde_json::to_value(&first).unwrap(),
        serde_json::to_value(&second).unwrap()
    );
    let mut selected = options(directory.path());
    selected.packages.push("a".into());
    assert_eq!(scan(&selected).unwrap().diagnostics.len(), 1);
    selected.packages.push("unknown".into());
    assert!(scan(&selected).is_err());
}

