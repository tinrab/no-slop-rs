#[test]
fn test_out_of_line_test_scope_propagates_but_shared_production_files_stay_checked() {
    let directory = workspace();
    write(
        directory.path(),
        "a/src/lib.rs",
        r#"
        #[cfg(test)] mod tests;
        mod runtime;
        #[path = "shared.rs"] mod shared;
        #[cfg(test)] #[path = "shared.rs"] mod shared_tests;

        #[cfg(test)] mod inline { mod child; }

        #[path = "../tests/shared_support.rs"] mod production_support;
    "#,
    );
    write(
        directory.path(),
        "a/src/tests.rs",
        "mod support;\n\nfn helper() -> Result<(), String> { loop {} }",
    );
    write(
        directory.path(),
        "a/src/tests/support.rs",
        "fn helper() -> Result<(), String> { loop {} }",
    );
    write(
        directory.path(),
        "a/src/inline/child.rs",
        "fn helper() -> Result<(), String> { loop {} }",
    );
    write(
        directory.path(),
        "a/src/runtime.rs",
        "fn f() -> Result<(), String> { loop {} }",
    );
    write(
        directory.path(),
        "a/src/shared.rs",
        "fn f() -> Result<(), String> { loop {} }",
    );
    write(
        directory.path(),
        "a/tests/shared_support.rs",
        "fn helper() -> Result<(), String> { loop {} }",
    );
    let mut selected = options(directory.path());
    selected.packages.push("a".into());
    let report = scan(&selected).unwrap();
    assert!(report.failures.is_empty(), "{:?}", report.failures);
    let paths: Vec<_> = report
        .diagnostics
        .iter()
        .map(|diagnostic| diagnostic.path.to_string_lossy())
        .collect();
    assert_eq!(
        paths,
        [
            "a/src/runtime.rs",
            "a/src/shared.rs",
            "a/tests/shared_support.rs"
        ]
    );
}

