#[test]
fn test_spacing_rule_supports_local_exceptions_and_configured_levels() {
    let report = source_report(
        "fn first() {}\n// no-slop-allow: require-readable-spacing -- intentionally grouped declarations\n#[inline]\nfn second() {}",
    );
    assert!(report.failures.is_empty(), "{:?}", report.failures);
    assert!(report.diagnostics.is_empty());
    assert_eq!(report.summary.suppressed, 1);

    for level in ["warn", "off"] {
        let config = Config::parse(&serde_json::json!({"no-slop": {"rules": {
            "require-readable-spacing": level
        }}}))
        .unwrap();
        let mut report = Report::default();
        scan_source(
            Path::new("src/lib.rs"),
            "fn first() {}\nfn second() {}",
            false,
            &config,
            &mut report,
        );
        assert_eq!(report.exit_status(), 0);
        match level {
            "warn" => {
                assert_eq!(report.diagnostics.len(), 1);
                assert_eq!(report.diagnostics[0].level, Level::Warn);
            }
            "off" => assert!(report.diagnostics.is_empty()),
            _ => unreachable!(),
        }
    }
}

